-- Invoice system for Barlas Print Studio
create sequence if not exists private.invoice_number_seq;

create table if not exists public.invoices (
  id uuid primary key default gen_random_uuid(),
  invoice_number text not null unique,
  order_id uuid not null unique references public.orders(id) on delete restrict,
  order_number text not null,
  user_id uuid not null,
  customer_name text not null,
  customer_email text not null,
  status text not null default 'draft'
    check (status in ('draft','sent','paid','overdue','void')),
  issue_date date not null default current_date,
  due_date date,
  subtotal numeric not null default 0 check (subtotal >= 0),
  gst numeric not null default 0 check (gst >= 0),
  total numeric not null default 0 check (total >= 0),
  notes text,
  sent_at timestamptz,
  paid_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.invoice_items (
  id bigint generated by default as identity primary key,
  invoice_id uuid not null references public.invoices(id) on delete cascade,
  product text not null,
  description text,
  quantity integer not null check (quantity > 0),
  unit_price numeric not null default 0 check (unit_price >= 0),
  line_total numeric not null default 0 check (line_total >= 0),
  created_at timestamptz not null default now()
);

create index if not exists invoices_user_created_idx on public.invoices(user_id,created_at desc);
create index if not exists invoice_items_invoice_idx on public.invoice_items(invoice_id);

alter table public.invoices enable row level security;
alter table public.invoice_items enable row level security;

drop policy if exists invoices_select_owner_or_admin on public.invoices;
create policy invoices_select_owner_or_admin on public.invoices
for select to authenticated
using (user_id=(select auth.uid()) or (select private.is_current_user_admin()));

drop policy if exists invoices_admin_insert on public.invoices;
create policy invoices_admin_insert on public.invoices
for insert to authenticated
with check ((select private.is_current_user_admin()));

drop policy if exists invoices_admin_update on public.invoices;
create policy invoices_admin_update on public.invoices
for update to authenticated
using ((select private.is_current_user_admin()))
with check ((select private.is_current_user_admin()));

drop policy if exists invoices_admin_delete on public.invoices;
create policy invoices_admin_delete on public.invoices
for delete to authenticated
using ((select private.is_current_user_admin()));

drop policy if exists invoice_items_select_owner_or_admin on public.invoice_items;
create policy invoice_items_select_owner_or_admin on public.invoice_items
for select to authenticated
using (
  exists (
    select 1 from public.invoices i
    where i.id=invoice_items.invoice_id
      and (i.user_id=(select auth.uid()) or (select private.is_current_user_admin()))
  )
);

drop policy if exists invoice_items_admin_insert on public.invoice_items;
create policy invoice_items_admin_insert on public.invoice_items
for insert to authenticated
with check ((select private.is_current_user_admin()));

drop policy if exists invoice_items_admin_update on public.invoice_items;
create policy invoice_items_admin_update on public.invoice_items
for update to authenticated
using ((select private.is_current_user_admin()))
with check ((select private.is_current_user_admin()));

drop policy if exists invoice_items_admin_delete on public.invoice_items;
create policy invoice_items_admin_delete on public.invoice_items
